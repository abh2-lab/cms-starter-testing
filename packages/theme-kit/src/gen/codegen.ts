import type { BlockField } from '@cms/blocks';
import type { BlockSpec } from './types.js';
import { toCamelCase, toPascalCase, toBlockComponentName } from '../lib/naming.js';
import { quote, fieldTsType, serializeFieldArray } from './serialize.js';
import { BLOCK_TYPES_IMPORT } from '../lib/paths.js';

// A `interface <Name> { key?: <type>; … }` from a field/option list. Members are
// optional, mirroring the existing blocks (hero.ts → `interface HeroFields`).
function tsInterface(name: string, fields: BlockField[]): string {
  const members = fields.map((f) => `  ${f.key}?: ${fieldTsType(f)};`).join('\n');
  return `interface ${name} {\n${members}\n}`;
}

// The load() (+ resolveBoxes for box) body, indented two spaces. Stubs compile
// cleanly under the repo's strict tsconfig: params the stub can't use generically
// are `_`-prefixed (the repo's discard convention — eslint argsIgnorePattern '^_'
// + TS noUnusedParameters both ignore them). The agent fills these in.
function loadBody(kind: BlockSpec['kind']): string {
  switch (kind) {
    case 'field':
      return [
        '  async load(ctx) {',
        '    // TODO(human): project the data this block renders from the current-post',
        '    // box (see blocks/post-title.ts). The composer sets ctx.box for descendants.',
        '    return { value: ctx.box?.content.title ?? null };',
        '  },',
      ].join('\n');
    case 'container':
      return [
        '  load() {',
        '    // Containers add layout/styling only: return null and render children via',
        '    // the default <slot/> (see blocks/group.ts).',
        '    return Promise.resolve(null);',
        '  },',
      ].join('\n');
    case 'box':
      return [
        '  load() {',
        '    // Box blocks carry no data of their own.',
        '    return Promise.resolve(null);',
        '  },',
        '  async resolveBoxes(_ctx, _args) {',
        '    // TODO(human): resolve the post box(es) — a single selector returns 1 box, a',
        '    // query loop returns N (see blocks/post.ts and blocks/query-loop.ts). Rename',
        '    // _ctx -> ctx and destructure { options } from the 2nd arg when you wire it up.',
        '    return [];',
        '  },',
      ].join('\n');
    case 'standalone':
    default:
      return [
        '  async load(_ctx, _args) {',
        '    // TODO(human): standalone blocks fetch their own data. Rename _ctx -> ctx,',
        '    // destructure { options } from the 2nd arg, then e.g. (see blocks/hero.ts):',
        "    //   const story = await ctx.fetchContent(String(options.content_type), String(options.slug));",
        '    //   return { story };',
        '    return {};',
        '  },',
    ].join('\n');
  }
}

// The SERVER half: packages/blocks/src/blocks/<key>.ts
export function renderServerBlock(spec: BlockSpec): string {
  const pascal = toPascalCase(spec.key);
  const camel = toCamelCase(spec.key);
  const hasFields = spec.fields.length > 0;
  const hasOptions = spec.options.length > 0;
  const fieldsType = hasFields ? `${pascal}Fields` : 'Record<string, unknown>';
  const optionsType = hasOptions ? `${pascal}Options` : 'Record<string, unknown>';

  const interfaces: string[] = [];
  if (hasFields) interfaces.push(tsInterface(`${pascal}Fields`, spec.fields));
  if (hasOptions) interfaces.push(tsInterface(`${pascal}Options`, spec.options));

  const meta: string[] = [
    `    key: ${quote(spec.key)},`,
    `    label: ${quote(spec.label)},`,
    `    category: ${quote(spec.category)},`,
  ];
  if (spec.description) meta.push(`    description: ${quote(spec.description)},`);
  if (spec.icon) meta.push(`    icon: ${quote(spec.icon)},`);
  if (spec.kind !== 'standalone') meta.push(`    kind: ${quote(spec.kind)},`);
  meta.push(`    fields: ${serializeFieldArray(spec.fields, '    ')},`);
  meta.push(`    options: ${serializeFieldArray(spec.options, '    ')},`);

  const parts: string[] = [
    `import type { Block } from '${BLOCK_TYPES_IMPORT}';`,
    '',
    `// ${spec.label} — generated by \`pnpm gen:block\`. TODO(human): document what`,
    '// this block renders, then replace the load() stub + the matching .vue render half.',
    '',
  ];
  if (interfaces.length) {
    parts.push(interfaces.join('\n'));
    parts.push('');
  }
  parts.push(`export const ${camel}: Block<${fieldsType}, ${optionsType}> = {`);
  parts.push('  meta: {');
  parts.push(meta.join('\n'));
  parts.push('  },');
  parts.push(loadBody(spec.kind));
  parts.push('};');
  parts.push('');
  return parts.join('\n');
}

// The RENDER half: apps/web/themes/default/app/components/blocks/Block<Pascal>.vue
export function renderVueComponent(spec: BlockSpec): string {
  const componentName = toBlockComponentName(spec.key);
  const hasFields = spec.fields.length > 0;
  const hasOptions = spec.options.length > 0;
  const fieldsType = hasFields ? 'Fields' : 'Record<string, unknown>';
  const optionsType = hasOptions ? 'BlockOptions' : 'Record<string, unknown>';
  const isWrapper = spec.kind === 'container' || spec.kind === 'box';

  const typeDecls: string[] = [];
  if (hasFields) typeDecls.push(tsInterface('Fields', spec.fields));
  if (hasOptions) typeDecls.push(tsInterface('BlockOptions', spec.options));

  const script: string[] = ['<script setup lang="ts">'];
  if (isWrapper) {
    script.push(
      `// ${componentName} — container/box render half for the '${spec.key}' block.`,
      '// Renders its children via the default <slot/>. Generated by `pnpm gen:block`.',
    );
  } else {
    script.push(
      `// ${componentName} — render half for the '${spec.key}' block. Generated by`,
      '// `pnpm gen:block`. TODO(human): replace the placeholder with the real design',
      '// and bind the fields/data your load() returns.',
    );
  }
  script.push('');
  if (typeDecls.length) {
    script.push(typeDecls.join('\n'));
  }
  if (!isWrapper) {
    script.push('interface Data {');
    script.push('  // TODO(human): mirror the shape your load() returns.');
    script.push('  [key: string]: unknown;');
    script.push('}');
  }
  script.push('');
  script.push('defineProps<{');
  script.push(`  fields: ${fieldsType};`);
  script.push(`  options: ${optionsType};`);
  script.push(`  data: ${isWrapper ? 'Record<string, unknown> | null' : 'Data | null'};`);
  script.push('}>();');
  script.push('</script>');

  const template = isWrapper
    ? [
        '<template>',
        `  <div class="block-${spec.key}">`,
        '    <slot />',
        '  </div>',
        '</template>',
      ]
    : [
        '<template>',
        `  <section class="block-${spec.key}">`,
        "    <!-- TODO(human): replace this placeholder with the block's real markup. -->",
        `    <p class="block-${spec.key}__stub">`,
        `      <strong>${spec.label} block</strong> — generated stub. Fill in the template.`,
        '    </p>',
        '  </section>',
        '</template>',
      ];

  const style = isWrapper
    ? [
        '<style scoped>',
        `.block-${spec.key} {`,
        '  display: flow-root;',
        '}',
        '</style>',
      ]
    : [
        '<style scoped>',
        `.block-${spec.key} {`,
        '  padding: 24px 20px;',
        '}',
        `.block-${spec.key}__stub {`,
        '  border: 1px dashed var(--border);',
        '  background: var(--surface);',
        '  border-radius: var(--radius);',
        '  padding: 16px;',
        '  color: var(--muted);',
        '  font-size: 14px;',
        '}',
        '</style>',
      ];

  return [script.join('\n'), '', template.join('\n'), '', style.join('\n'), ''].join('\n');
}
