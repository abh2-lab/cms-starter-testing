import type { TemplateBlock } from '@cms/blocks';
import type { TemplateSpec } from './types.js';
import { toCamelCase } from '../lib/naming.js';
import { quote, serializeValue } from './serialize.js';
import { PART_TYPES_IMPORT, TEMPLATE_TYPES_IMPORT } from '../lib/paths.js';

// Serialize a Record<string, unknown> (default_fields / default_options) as a TS
// object literal. Bareword keys stay unquoted; anything non-identifier is quoted.
function isPartRole(role: string | undefined): boolean {
  return role === 'header' || role === 'footer' || role === 'sidebar';
}

function serializeRecord(obj: Record<string, unknown>, indent: string): string {
  const keys = Object.keys(obj);
  if (keys.length === 0) return '{}';
  const inner = indent + '  ';
  const lines = keys.map((k) => {
    const keyText = /^[a-z][a-z0-9_]*$/i.test(k) ? k : quote(k);
    return `${inner}${keyText}: ${serializeValue(obj[k])},`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function serializeTemplateBlock(block: TemplateBlock, indent: string): string {
  const inner = indent + '  ';
  const lines: string[] = [`${indent}{`];
  lines.push(`${inner}block_key: ${quote(block.block_key)},`);
  lines.push(`${inner}default_fields: ${serializeRecord(block.default_fields, inner)},`);
  lines.push(`${inner}default_options: ${serializeRecord(block.default_options, inner)},`);
  if (block.children && block.children.length > 0) {
    const kids = block.children.map((c) => serializeTemplateBlock(c, inner + '  ')).join('\n');
    lines.push(`${inner}children: [\n${kids}\n${inner}],`);
  }
  lines.push(`${indent}},`);
  return lines.join('\n');
}

function serializeBlocks(blocks: TemplateBlock[], indent: string): string {
  if (blocks.length === 0) return '[]';
  const items = blocks.map((b) => serializeTemplateBlock(b, indent + '  ')).join('\n');
  return `[\n${items}\n${indent}]`;
}

// The template/part file: packages/blocks/src/{templates,parts}/<key>.ts
export function renderTemplate(spec: TemplateSpec): string {
  const camel = toCamelCase(spec.key);
  const meta: string[] = [`  key: ${quote(spec.key)},`, `  name: ${quote(spec.name)},`];
  if (spec.description) meta.push(`  description: ${quote(spec.description)},`);
  if (spec.previewImage) meta.push(`  previewImage: ${quote(spec.previewImage)},`);
  if (spec.role) meta.push(`  role: ${quote(spec.role)},`);
  meta.push(`  version: ${String(spec.version)},`);
  meta.push(`  blocks: ${serializeBlocks(spec.blocks, '  ')},`);

  return [
    `import type { TemplateMeta } from '${isPartRole(spec.role) ? PART_TYPES_IMPORT : TEMPLATE_TYPES_IMPORT}';`,
    '',
    `// ${spec.name} — generated by \`pnpm gen:template\`. Every block_key below must`,
    '// exist in the block registry (verify:theme checks this).',
    '',
    `export const ${camel}: TemplateMeta = {`,
    meta.join('\n'),
    '};',
    '',
  ].join('\n');
}
